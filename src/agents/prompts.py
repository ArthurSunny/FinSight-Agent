def build_verifier_user_message(
    evidence_text: str,
    queries: list[dict],
    *,
    pdf_period: str,
    financial_period: str,
) -> str:
    """组装附注核查节点的用户消息。"""
    import json

    period_note = (
        f"注意：附注 PDF 的报告期为 **{pdf_period}**，而财务数据最新期次为 **{financial_period}**。"
        + (
            "两者**不一致**，请在 period_note 中说明，并在引用时明确标注 PDF 实际期次。"
            if pdf_period != financial_period
            else "两者一致。"
        )
    )
    return f"""## 待核查疑点（来自审计会计师的 footnote_queries）
{json.dumps(queries, ensure_ascii=False, indent=2)}

## 检索到的年报附注原文（唯一可用证据，含页码）
{evidence_text}

## 期次对齐要求
{period_note}

请逐条给出核查结论，严格按 JSON 契约输出。"""


def build_fact_pack_message(fact_pack: str) -> str:
    """把事实包包裹成带边界标记的用户消息片段。"""
    return f"{FACT_PACK_START}\n{fact_pack}\n{FACT_PACK_END}"


def build_editor_user_message(
    fact_pack: str,
    fundamental: dict,
    forensic: dict,
    peer_analysis: dict,
    *,
    audit_feedback: list[str] | None = None,
    previous_markdown: str = "",
    rag_evidences: dict | None = None,
    rag_note: str = "",
) -> str:
    """组装首席撰稿人的用户消息（含三位专家结论、附注穿透证据与重写反馈）。"""
    import json

    parts = [
        build_fact_pack_message(fact_pack),
        "\n## 专家结论 A：基本面与杜邦归因\n"
        + json.dumps(fundamental, ensure_ascii=False, indent=2),
        "\n## 专家结论 B：CPA 舞弊排雷审计\n" + json.dumps(forensic, ensure_ascii=False, indent=2),
        "\n## 专家结论 C：同业对标研究\n" + json.dumps(peer_analysis, ensure_ascii=False, indent=2),
    ]
    if rag_evidences and rag_evidences.get("evidences"):
        parts.append(
            "\n## 附注穿透证据（Phase 3 RAG 结果，第六章必须使用）\n"
            + json.dumps(rag_evidences, ensure_ascii=False, indent=2)
            + "\n请把每条证据的页码（如 P.91）与核查结论原样写进第六章，"
            "并补充仍需人工核查的事项。"
        )
    elif rag_note:
        parts.append(
            "\n## 附注穿透状态\n"
            + rag_note
            + "\n第六章请按「无附注证据」的要求书写：明确说明未获取 PDF，再列出待核查清单。"
        )
    if audit_feedback:
        parts.append(
            "\n## 【上一版报告未通过自动质检，必须逐条修正】\n"
            + "\n".join(f"- {item}" for item in audit_feedback)
        )
        if previous_markdown:
            parts.append("\n## 上一版报告全文（供你定位并修正问题）\n" + previous_markdown)
        parts.append(
            "\n请重新输出完整的六个章节。**修正时必须保持所有数字与事实包完全一致**，"
            "并确保每个核心数字都带报告期、金额单位统一为「亿元」。"
        )
    return "\n".join(parts)
