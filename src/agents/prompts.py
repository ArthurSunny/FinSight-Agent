"""Prompt 模板与 JSON 契约（唯一来源：与 fact_check 共享必选章节定义）。

设计原则
--------
1. **事实包隔离**：用户消息里的事实包用 ``<<<FACT_PACK>>>`` / ``<<<END_FACT_PACK>>>``
   包裹，既可防止模型把提示词与数据混淆，也让离线模板能精确截取同一段文本。
2. **契约先行**：每个 Agent 的 JSON 字段在提示词里显式列出，配合
   ``response_format={"type":"json_object"}`` 把"自由发挥"压到最低。
3. **引用强制**：所有数字必须带报告期；禁止编造事实包之外的数字。
"""

from __future__ import annotations

FACT_PACK_START = "<<<FACT_PACK>>>"
FACT_PACK_END = "<<<END_FACT_PACK>>>"

#: 报告必选章节：(中文序号, 标题)。fact_check 与 chief_editor 提示词共用此定义。
REQUIRED_SECTIONS: tuple[tuple[str, str], ...] = (
    ("一", "核心投研结论与财务健康度总览"),
    ("二", "成长性与杜邦 ROE 归因拆解"),
    ("三", "现金流含金量与资产负债表稳健性"),
    ("四", "CPA 财务排雷与 M-Score 审计意见"),
    ("五", "同业横向竞争财务对标"),
    ("六", "年报附注穿透核查与尽调追问清单"),
)

#: 报告标题
REPORT_TITLE = "FinSight 深度财务体检与排雷纪要（Tear Sheet）"


def _sections_outline() -> str:
    return "\n".join(f"## {idx}、{title}" for idx, title in REQUIRED_SECTIONS)


